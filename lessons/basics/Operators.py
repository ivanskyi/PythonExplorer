# Floor division operator
floor_division_result = 7 // 3
print("Floor division result:", floor_division_result)

# Exponentiation operator
exponentiation_result = 2 ** 4
print("Exponentiation result:", exponentiation_result)

# Remainder operator
remainder_result = 10 % 3
print("Remainder result:", remainder_result)

# Equality
print("Equality result:", 5 == 6)

# Logical Operators
result = 8 > 5 and "Oleh" == "Oleh"
print("Logical result:", result)
